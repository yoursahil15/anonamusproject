// ================= PAGE =================

export default function DocumentApproval() {
  const [documents, setDocuments] = useState([]);
  const [user, setUser] = useState(null);
  const [loading, setLoading] = useState(true);
  const [processingId, setProcessingId] = useState("");
  const [downloadingId, setDownloadingId] = useState("");
  const [search, setSearch] = useState("");
  const [statusFilter, setStatusFilter] = useState("ALL");
  const [error, setError] = useState("");

  // Synchronous guards against duplicate submissions (state updates are async).
  const processingRef = useRef(false);
  const downloadingRef = useRef(false);

  const navigate = useNavigate();

  // ================= USER & PERMISSIONS =================

  useEffect(() => {
    try {
      const storedUser = JSON.parse(localStorage.getItem("user") || "null");
      setUser(storedUser);
    } catch (err) {
      console.error("Failed to read user:", err);
      setUser(null);
    }
  }, []);

  const permissions = useMemo(() => {
    const rawPermissions = user?.permissions;

    if (Array.isArray(rawPermissions)) return rawPermissions;
    if (typeof rawPermissions === "string") return [rawPermissions];

    return [];
  }, [user]);

  // ================= FETCH DOCUMENTS =================

  const fetchDocuments = useCallback(async () => {
    try {
      setLoading(true);
      setError("");

      // Tenant accounts must use the tenant-scoped API. The legacy
      // /documents/approval-documents route is intentionally blocked for them.
      const storedUser = JSON.parse(localStorage.getItem("user") || "null");
      const res = storedUser?.tenantId
        ? await API.get("/tenant/documents", { params: { limit: 100 } })
        : await API.get("/documents/approval-documents");
      const rows = storedUser?.tenantId ? res.data?.data : res.data;
      setDocuments(Array.isArray(rows) ? rows : []);
    } catch (err) {
      console.error("Failed to fetch documents:", err);
      setError("Unable to load documents. Please try again.");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    fetchDocuments();
  }, [fetchDocuments]);

  // ================= APPROVAL ACTIONS =================

  const performAction = useCallback(
    async (documentId, action, workflow) => {
      if (processingRef.current) return;

      let reason = "";

      if (action === "reject") {
        reason = window.prompt("Enter the reason for rejection:");

        if (reason === null) return;

        reason = reason.trim();

        if (!reason) {
          window.alert("Rejection reason is required.");
          return;
        }
      }

      let storedUser = null;
      try {
        storedUser = JSON.parse(localStorage.getItem("user") || "null");
      } catch {
        // The request will use the legacy route if no valid tenant profile exists.
      }
      const endpoint = storedUser?.tenantId
        ? workflow === "checker"
          ? `/tenant/documents/${documentId}/check`
          : `/tenant/documents/${documentId}/approve`
        : workflow === "checker"
          ? `/documents/checker-action/${documentId}`
          : `/documents/approver-action/${documentId}`;

      try {
        processingRef.current = true;
        setProcessingId(documentId);
        setError("");

        if (storedUser?.tenantId) await API.post(endpoint, { action, reason });
        else await API.put(endpoint, { action, reason });

        window.alert(
          action === "approve"
            ? workflow === "checker"
              ? "Document checked successfully."
              : "Document approved successfully."
            : "Document rejected successfully.",
        );

        await fetchDocuments();
      } catch (err) {
        console.error(`${workflow} action failed:`, err);
        window.alert(err.response?.data?.msg || `${workflow} action failed.`);
      } finally {
        processingRef.current = false;
        setProcessingId("");
      }
    },
    [fetchDocuments],
  );

  const checkerAction = useCallback(
    (documentId, action) => performAction(documentId, action, "checker"),
    [performAction],
  );

  const approverAction = useCallback(
    (documentId, action) => performAction(documentId, action, "approver"),
    [performAction],
  );

  // ================= EDIT DOCUMENT =================

  const handleEdit = useCallback(
    (doc) => {
      navigate(`/edit-document/${doc._id}`, {
        state: {
          documentType: doc.documentType,
          companyId: doc.company?._id,
          documentId: doc._id,
        },
      });
    },
    [navigate],
  );

  // ================= DOWNLOAD DOCUMENT =================

  const handleDownload = useCallback(async (doc) => {
    if (downloadingRef.current) return;

    try {
      downloadingRef.current = true;
      setDownloadingId(doc._id);

      const storedUser = JSON.parse(localStorage.getItem("user") || "null");
      const fileEndpoint = storedUser?.tenantId
        ? `/tenant/documents/${doc._id}/download`
        : `/documents/generated/${doc._id}/file`;
      const response = await API.get(fileEndpoint, {
        responseType: "blob",
      });

      const url = URL.createObjectURL(response.data);
      const link = document.createElement("a");

      link.href = url;
      link.download = doc.fileName || doc.documentType || "document";
      document.body.appendChild(link);
      link.click();
      link.remove();

      window.setTimeout(() => URL.revokeObjectURL(url), 1000);
    } catch (err) {
      console.error("Document download failed:", err);

      window.alert(
        err.response?.status === 410
          ? "This legacy document needs to be migrated to server storage."
          : "Document download failed. Please try again.",
      );
    } finally {
      downloadingRef.current = false;
      setDownloadingId("");
    }
  }, []);

  // ================= SEARCH & FILTER =================

  const filteredDocuments = useMemo(() => {
    const query = search.trim().toLowerCase();

    return documents.filter((doc) => {
      const matchesStatus =
        statusFilter === "ALL" ||
        (statusFilter === REJECTED_GROUP
          ? doc.status === "REJECTED_BY_CHECKER" ||
            doc.status === "REJECTED_BY_APPROVER"
          : doc.status === statusFilter);

      if (!matchesStatus) return false;
      if (!query) return true;

      return (
        (doc.company?.nameOfCompany || "").toLowerCase().includes(query) ||
        (doc.documentType || "").toLowerCase().includes(query) ||
        (doc.fileName || "").toLowerCase().includes(query)
      );
    });
  }, [documents, search, statusFilter]);

  const hasActiveFilters = search.trim() !== "" || statusFilter !== "ALL";

  const resetFilters = useCallback(() => {
    setSearch("");
    setStatusFilter("ALL");
  }, []);

  // ================= SUMMARY =================

  const summary = useMemo(() => {
    const counts = {
      total: documents.length,
      pendingCheck: 0,
      pendingApproval: 0,
      approved: 0,
      rejected: 0,
    };

    for (const doc of documents) {
      if (doc.status === "PENDING_CHECK") counts.pendingCheck += 1;
      else if (doc.status === "PENDING_APPROVAL") counts.pendingApproval += 1;
      else if (doc.status === "APPROVED") counts.approved += 1;
      else if (
        doc.status === "REJECTED_BY_CHECKER" ||
        doc.status === "REJECTED_BY_APPROVER"
      )
        counts.rejected += 1;
    }

    return counts;
  }, [documents]);

  // ================= ACTIONS =================

  const renderActions = (doc) => {
    const busy = processingId === doc._id;
    const anyBusy = Boolean(processingId);
    const downloading = downloadingId === doc._id;

    return (
      <div className="flex flex-wrap items-center gap-1.5 lg:justify-end">
        <ActionButton
          onClick={() => handleDownload(doc)}
          disabled={downloading || busy}
          title="Download document"
        >
          {downloading ? (
            <Loader2 size={14} className="animate-spin" />
          ) : (
            <Download size={14} />
          )}
          Download
        </ActionButton>

        {(permissions.includes("maker") || permissions.includes("checker")) &&
          doc.status === "REJECTED_BY_CHECKER" && (
            <ActionButton
              variant="warning"
              onClick={() => handleEdit(doc)}
              disabled={busy}
              title="Edit and resubmit document"
            >
              <Pencil size={14} />
              Edit
            </ActionButton>
          )}

        {permissions.includes("checker") && doc.status === "PENDING_CHECK" && (
          <>
            <ActionButton
              variant="success"
              onClick={() => checkerAction(doc._id, "approve")}
              disabled={anyBusy}
              title="Mark document as checked"
            >
              {busy ? (
                <Loader2 size={14} className="animate-spin" />
              ) : (
                <Check size={7} />
              )}
              {busy ? "Processing" : "Check"}
            </ActionButton>

            <ActionButton
              variant="danger"
              onClick={() => checkerAction(doc._id, "reject")}
              disabled={anyBusy}
              title="Reject document"
            >
              <X size={7} />
              Reject
            </ActionButton>
          </>
        )}

        {permissions.includes("approver") &&
          doc.status === "PENDING_APPROVAL" && (
            <>
              <ActionButton
                variant="success"
                onClick={() => approverAction(doc._id, "approve")}
                disabled={anyBusy}
                title="Approve document"
              >
                {busy ? (
                  <Loader2 size={14} className="animate-spin" />
                ) : (
                  <Check size={14} />
                )}
                {busy ? "Processing" : "Approve"}
              </ActionButton>

              <ActionButton
                variant="danger"
                onClick={() => approverAction(doc._id, "reject")}
                disabled={anyBusy}
                title="Reject document"
              >
                <X size={14} />
                Reject
              </ActionButton>
            </>
          )}
      </div>
    );
  };

  // ================= LIST STATES =================

  const renderState = () => {
    if (loading) {
      return (
        <StateMessage
          icon={Loader2}
          tone="animate-spin text-blue-600"
          title="Loading documents…"
        />
      );
    }

    if (error && documents.length === 0) {
      return (
        <StateMessage
          icon={AlertCircle}
          tone="text-red-500"
          title="Couldn't load documents"
          text={error}
          action={
            <button
              type="button"
              onClick={fetchDocuments}
              className="mt-3 inline-flex h-8 items-center gap-1.5 rounded-lg bg-blue-600 px-3 text-xs font-medium text-white transition hover:bg-blue-700 focus:outline-none focus-visible:ring-2 focus-visible:ring-blue-500 focus-visible:ring-offset-1"
            >
              <RefreshCw size={14} />
              Retry
            </button>
          }
        />
      );
    }

    if (documents.length === 0) {
      return (
        <StateMessage
          icon={Inbox}
          title="No documents yet"
          text="Documents sent for checking or approval will appear here."
        />
      );
    }

    if (filteredDocuments.length === 0) {
      return (
        <StateMessage
          icon={SearchX}
          title="No matching documents"
          text="Try a different search term or status."
          action={
            <button
              type="button"
              onClick={resetFilters}
              className="mt-3 inline-flex h-8 items-center gap-1.5 rounded-lg border border-slate-200 bg-white px-3 text-xs font-medium text-slate-700 transition hover:bg-slate-50 focus:outline-none focus-visible:ring-2 focus-visible:ring-blue-500"
            >
              <FilterX size={14} />
              Reset filters
            </button>
          }
        />
      );
    }

    return null;
  };

  const stateView = renderState();

  // ================= UI =================

  return (
    <div className="min-h-full">
      <div className="mx-auto max-w-[1600px] space-y-3">
        {/* HEADER */}
        <header className="flex items-center justify-between gap-3">
          <div className="flex min-w-0 items-center gap-3">
            <div className="flex h-9 w-9 shrink-0 items-center justify-center rounded-lg bg-blue-600 text-white shadow-sm">
              <ShieldCheck size={19} />
            </div>
            <div className="min-w-0">
              <h1 className="text-lg font-semibold leading-tight text-slate-900">
                Document Approval
              </h1>
              <p className="truncate text-xs text-slate-500">
                Review and manage document approval workflows.
              </p>
            </div>
          </div>

          <button
            type="button"
            onClick={fetchDocuments}
            disabled={loading}
            className="inline-flex h-8 shrink-0 items-center gap-1.5 rounded-lg border border-slate-200 bg-white px-2.5 text-xs font-medium text-slate-700 shadow-sm transition hover:bg-slate-50 focus:outline-none focus-visible:ring-2 focus-visible:ring-blue-500 disabled:cursor-not-allowed disabled:opacity-50"
          >
            <RefreshCw size={14} className={loading ? "animate-spin" : ""} />
            <span className="hidden sm:inline">Refresh</span>
          </button>
        </header>

        {/* SUMMARY */}
        <div className="grid grid-cols-2 gap-2 sm:grid-cols-3 xl:grid-cols-5">
          {SUMMARY_CARDS.map((card) => (
            <SummaryCard
              key={card.key}
              label={card.label}
              value={summary[card.key]}
              icon={card.icon}
              tone={card.tone}
              filterValue={card.filterValue}
              active={statusFilter === card.filterValue}
              onSelect={setStatusFilter}
            />
          ))}
        </div>

        {/* ERROR BANNER (when stale data is still shown, e.g. a failed refresh) */}
        {error && documents.length > 0 && (
          <div
            role="alert"
            className="flex items-center gap-2 rounded-lg border border-red-200 bg-red-50 px-3 py-2 text-xs text-red-700"
          >
            <AlertCircle size={14} className="shrink-0" />
            <span className="flex-1">{error}</span>
            <button
              type="button"
              onClick={fetchDocuments}
              className="font-semibold underline underline-offset-2 focus:outline-none focus-visible:ring-2 focus-visible:ring-red-500"
            >
              Retry
            </button>
          </div>
        )}

        {/* MAIN PANEL */}
        <section className="overflow-hidden rounded-xl border border-slate-200 bg-white shadow-sm">
          {/* TOOLBAR */}
          <div className="flex flex-col gap-2 border-b border-slate-200 px-3 py-2.5 sm:flex-row sm:items-center sm:justify-between">
            <p className="text-xs text-slate-500" aria-live="polite">
              {loading ? (
                "Loading…"
              ) : (
                <>
                  <span className="font-semibold text-slate-800">
                    {filteredDocuments.length}
                  </span>{" "}
                  of {documents.length} documents
                </>
              )}
            </p>

            <div className="flex flex-col gap-2 sm:flex-row sm:items-center">
              <div className="relative sm:w-64">
                <Search
                  size={14}
                  className="pointer-events-none absolute left-2.5 top-1/2 -translate-y-1/2 text-slate-400"
                />
                <input
                  type="text"
                  value={search}
                  onChange={(e) => setSearch(e.target.value)}
                  placeholder="Search company, type or file name"
                  aria-label="Search documents"
                  className="h-8 w-full rounded-lg border border-slate-200 bg-white pl-8 pr-2.5 text-xs text-slate-800 outline-none transition placeholder:text-slate-400 focus:border-blue-400 focus:ring-2 focus:ring-blue-100"
                />
              </div>

              <select
                value={statusFilter}
                onChange={(e) => setStatusFilter(e.target.value)}
                aria-label="Filter documents by status"
                className="h-8 rounded-lg border border-slate-200 bg-white px-2.5 text-xs text-slate-700 outline-none transition focus:border-blue-400 focus:ring-2 focus:ring-blue-100"
              >
                {STATUS_OPTIONS.map((option) => (
                  <option key={option.value} value={option.value}>
                    {option.label}
                  </option>
                ))}
              </select>

              {hasActiveFilters && (
                <button
                  type="button"
                  onClick={resetFilters}
                  className="inline-flex h-8 items-center justify-center gap-1.5 rounded-lg px-2.5 text-xs font-medium text-blue-700 transition hover:bg-blue-50 focus:outline-none focus-visible:ring-2 focus-visible:ring-blue-500"
                >
                  <FilterX size={14} />
                  Reset
                </button>
              )}
            </div>
          </div>

          {stateView ? (
            stateView
          ) : (
            <>
              {/* DESKTOP TABLE */}
              <div className="hidden lg:block">
                <table className="w-full table-fixed text-left">
                  <colgroup>
                    <col className="w-[27%]" />
                    <col className="w-[20%]" />
                    <col className="w-[30%]" />
                    <col className="w-[20%]" />
                  </colgroup>
                  <thead>
                    <tr className="border-b border-slate-200 bg-slate-50 text-[11px] font-semibold text-slate-500">
                      <th className="px-4 py-2">Company / Document</th>
                      <th className="px-3 py-2">Status</th>
                      <th className="px-3 py-3">Activity History</th>
                      <th className="px-4 py-2 text-right">Actions</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-100">
                    {filteredDocuments.map((doc) => (
                      <tr
                        key={doc._id}
                        className="align-top transition-colors hover:bg-slate-50/80"
                      >
                        <td className="px-4 py-2.5">
                          <DocumentInfo doc={doc} />
                        </td>
                        <td className="px-3 py-2.5">
                          <StatusBadge status={doc.status} />
                        </td>
                        <td className="px-3 py-2.5">
                          <Activity doc={doc} />
                        </td>
                        <td className="px-4 py-2.5">{renderActions(doc)}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>

              {/* TABLET / MOBILE CARDS */}
              <div className="space-y-2 p-2.5 lg:hidden">
                {filteredDocuments.map((doc) => (
                  <article
                    key={doc._id}
                    className="rounded-lg border border-slate-200 bg-white p-3"
                  >
                    <div className="flex items-start justify-between gap-2">
                      <div className="min-w-0 flex-1">
                        <DocumentInfo doc={doc} />
                      </div>
                      <StatusBadge status={doc.status} />
                    </div>

                    <div className="mt-2.5 border-t border-slate-100 pt-2.5">
                      <p className="mb-1.5 flex items-center gap-1.5 text-[11px] font-medium text-slate-500">
                        <History size={12} />
                        Activity History
                      </p>
                      <Activity doc={doc} />
                    </div>

                    <div className="mt-2.5 border-t border-slate-100 pt-2.5">
                      {renderActions(doc)}
                    </div>
                  </article>
                ))}
              </div>
            </>
          )}
        </section>
      </div>
    </div>
  );
}
