const Activity = memo(function Activity({ doc }) {
  const rejectedByChecker = doc.status === "REJECTED_BY_CHECKER";
  const rejectedByApprover = doc.status === "REJECTED_BY_APPROVER";

  return (
    <div className="min-w-0 space-y-1">
      <ActivityItem
        label="Generated by"
        person={
          doc.maker?.permissions?.includes("superadmin")
            ? "Superadmin"
            : getFullName(doc.maker)
        }
        dot="bg-blue-500"
      />

      {doc.checkedAt && (
        <ActivityItem
          label="Checked by"
          person={getFullName(doc.checker)}
          dot="bg-violet-500"
        />
      )}

      {doc.approvedAt && (
        <ActivityItem
          label="Approved by"
          person={getFullName(doc.approver)}
          dot="bg-emerald-500"
        />
      )}

      {(rejectedByChecker || rejectedByApprover) && (
        <ActivityItem
          label={
            rejectedByChecker ? "Rejected by checker" : "Rejected by approver"
          }
          person={getFullName(rejectedByChecker ? doc.checker : doc.approver)}
          dot="bg-red-500"
        />
      )}

      {doc.rejectedReason && (
        <div className="mt-1 rounded-md border border-red-100 bg-red-50/70 px-2 py-1.5">
          <p className="text-[11px] font-medium text-red-700">
            Rejection reason
          </p>
          <p className="mt-0.5 line-clamp-3 break-words text-xs text-red-600">
            {doc.rejectedReason}
          </p>
        </div>
      )}
    </div>
  );
});

